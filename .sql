Задание 6 | Сортировка по и ограничение для бизнес-вопросов

SELECT
  product_id,
  SUM(total_sales) AS total_revenue
FROM sales
GROUP BY product_id
ORDER BY total_revenue DESC
LIMIT 5;

-- Запрос агрегирует общую выручку по каждому продукту, сортирует результаты по убыванию выручки и ограничивает вывод первыми 5 продуктами с наибольшей выручкой.
-- Это позволяет быстро получить ответ на бизнес-вопрос о топ-5 продуктах по выручке.
-- Использование ORDER BY total_revenue DESC сортирует результаты по убыванию общей выручки.
-- Использование LIMIT 5 ограничивает количество возвращаемых строк до пяти.
-- Такой подход эффективен для получения ключевой информации без необходимости обработки всех данных.

EXPLAIN
SELECT
  product_id,
  SUM(total_sales) AS total_revenue
FROM sales
GROUP BY product_id
ORDER BY total_revenue DESC
LIMIT 5;

-- Использование EXPLAIN для анализа плана выполнения запроса с сортировкой и ограничением.

QUERY PLAN
"Limit  (cost=145.90..145.91 rows=5 width=36)"
"  ->  Sort  (cost=145.90..146.15 rows=100 width=36)"
"        Sort Key: (sum(total_sales)) DESC"
"        ->  HashAggregate  (cost=142.99..144.24 rows=100 width=36)"
"              Group Key: product_id"
"              ->  Seq Scan on sales  (cost=0.00..117.99 rows=4999 width=10)"

-- В данном плане выполнения видно, что запрос включает этап сортировки (Sort) и ограничение (Limit) после агрегации.
-- Это указывает на то, что оптимизатор запросов правильно обрабатывает сортировку и ограничение результатов.
-- Однако, как и ранее, используется последовательное сканирование (Seq Scan) по таблице sales.
-- Для дальнейшего улучшения производительности можно рассмотреть дополнительные оптимизации, такие как использование индексов или изменение структуры данных.
-- Важно регулярно проверять планы выполнения запросов, особенно после внесения изменений в структуру таблиц или добавления индексов.
-- Это помогает убедиться, что запросы выполняются эффективно и используют доступные оптимизации.


Задание 7 | Сравнение эффективности при использовании различных методов и методов, сгруппированных по категориям

Получите уникальные комбинации параметров category и price используя оба подхода.

EXPLAIN
SELECT DISTINCT
  category,
  price
FROM products;

QUERY PLAN
"HashAggregate  (cost=3.55..4.58 rows=103 width=15)"
"  Group Key: category, price"
"  ->  Seq Scan on products  (cost=0.00..3.03 rows=103 width=15)"


EXPLAIN
SELECT
  category,
  price
FROM products
GROUP BY category, price;

QUERY PLAN

"HashAggregate  (cost=3.55..4.58 rows=103 width=15)"
"  Group Key: category, price"
"  ->  Seq Scan on products  (cost=0.00..3.03 rows=103 width=15)"

-- В обоих случаях план выполнения показывает использование хеш-агрегации (HashAggregate) для получения уникальных комбинаций category и price.
-- Оба подхода имеют схожую стоимость выполнения и используют последовательное сканирование (Seq Scan) по таблице products.
-- В данном случае оба метода эффективны и дают одинаковые планы выполнения.
-- Однако в других сценариях один из методов может быть предпочтительнее в зависимости от структуры данных и конкретных требований запроса.
-- Важно анализировать планы выполнения запросов для выбора наиболее эффективного подхода в каждом конкретном случае.
-- Оба запроса дают одинаковый результат, но могут иметь разные планы выполнения в зависимости от структуры данных и индексов.

Почему PostgreSQL может оптимизировать их одинаковым образом?

-- PostgreSQL использует оптимизатор запросов, который анализирует запросы и выбирает наиболее эффективный план выполнения на основе статистики о данных.
-- В данном случае оба запроса приводят к одинаковому плану выполнения, потому что они оба требуют агрегации данных по тем же столбцам (category и price).
-- Оптимизатор определяет, что оба запроса могут быть выполнены с использованием хеш-агрегации и последовательного сканирования таблицы products.
-- Таким образом, несмотря на различия в синтаксисе, оба запроса приводят к одинаковым операциям на уровне выполнения, что объясняет одинаковую оптимизацию.


