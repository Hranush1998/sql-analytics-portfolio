Задание 9 | Размышление (краткий ответ)

Какие ограничения приносят наибольшую коммерческую выгоду?

-- Ограничения, такие как NOT NULL, UNIQUE и CHECK, обеспечивают целостность данных и предотвращают ошибки в бизнес-процессах. Например, ограничение NOT NULL гарантирует, что все необходимые поля заполнены, а UNIQUE предотвращает дублирование уникальных значений. Эти ограничения помогают избежать проблем с данными и обеспечивают надежность системы.

Какой индекс вы бы отдали приоритет в производственной среде?

-- В производственной среде я бы отдал приоритет индексу на столбец, который часто используется в WHERE-условиях и JOIN-ах. Например, если таблица `customers` часто используется в запросах с фильтрацией по `customer_id`, то индекс на этом столбце будет наиболее полезным.

Какие сигналы указывают на необходимость оптимизации запроса?

-- Сигналы, указывающие на необходимость оптимизации запроса, включают длительное время выполнения запросов, высокую нагрузку на базу данных, использование последовательного сканирования вместо индексов,
 а также планы выполнения запросов с высокой стоимостью. Анализируя эти факторы, можно определить, какие запросы требуют оптимизации для улучшения производительности.

Какой метод оптимизации запросов вы считаете наиболее эффективным?

-- Наиболее эффективным методом оптимизации запросов я считаю использование индексов, так как они значительно ускоряют поиск и фильтрацию данных. Кроме того, оптимизация запросов путем выбора только необходимых столбцов и использования агрегатных функций также способствует улучшению производительности.

